export const COUNTRIES = RAW.map(([code, name, capital, continent, nameAliases = [], capitalAliases = []]) => ({
  code, name, capital, continent,
  region: continent === 'na' || continent === 'sa' ? 'am' : continent,
  nameAliases, capitalAliases,
}));

export function countriesFor(region) {
  return region === 'world' ? COUNTRIES : COUNTRIES.filter(c => c.region === region);
}

// Minuscules, sans accents ni ponctuation : "Côte d'Ivoire" -> "cotedivoire"
export function normalize(s) {
  return s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/œ/g, 'oe').replace(/[^a-z0-9]/g, '');
}

export function acceptedAnswers(country, kind) {
  const list = kind === 'flags' ? [country.name, ...country.nameAliases] : [country.capital, ...country.capitalAliases];
  return [...new Set(list.map(normalize))];
}

export function flagEmoji(code) {
  return String.fromCodePoint(...[...code.toUpperCase()].map(c => 0x1f1e6 + c.charCodeAt(0) - 65));
}
